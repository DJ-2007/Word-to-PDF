export function getToolBySlug(slug: string): ConversionToolDefinition | undefined {
  return CONVERSION_TOOLS.find((t) => t.slug === slug);
}

export function getRelatedTools(slug: string, limit = 4): ConversionToolDefinition[] {
  const current = getToolBySlug(slug);
  if (!current) return CONVERSION_TOOLS.slice(0, limit);

  return CONVERSION_TOOLS.filter((t) => t.slug !== slug && (t.category === current.category || t.popular)).slice(0, limit);
}
